-- Exceptions Center: acknowledgements keep a noisy rule quiet once someone has looked at it.
CREATE TABLE exception_acks (
  key        varchar(120) PRIMARY KEY,
  note       varchar(250),
  acked_by   integer REFERENCES users(id),
  acked_at   timestamptz NOT NULL DEFAULT now()
);
